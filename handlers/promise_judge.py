def group_survives(g):
    """Вирок за властивостями, які назвала модель. ОКРЕМОЮ функцією — щоб
    правило можна було перевірити тестом без звернення до моделі: саме на
    цьому місці три правки промпту поспіль зробили гірше.

    Зливаємо у двох випадках і тільки в них:
      • та сама дія, яку неможливо виконати нарізно (одне зобов'язання,
        записане двічі);
      • стадія і результат однієї справи (за нею стежать як за однією темою).
    """
    # Об'єкт — умова ОБОВ'ЯЗКОВА для обох шляхів. Живий прогін 18.08 показав,
    # чому: у 14 з 40 підтверджених пар суддя САМ писав у поясненні «але це
    # різні підприємства / різні території / різні об'єкти» — і пара все одно
    # проходила, бо дія справді була та сама. Питання про об'єкт не ставилось
    # узагалі, тож модель відповідала на нього в тексті, а не в даних.
    if not g.get("same_object"):
        return False
    same_act = bool(g.get("same_action")) and not g.get("doable_separately")
    return same_act or bool(g.get("stage_of_same_result"))


def _group_block(article, records):
    out = [f"{article.get('label') or 'НОВИНА'}: {article.get('title') or '—'}"]
    text = (article.get("text") or "").strip()
    if text:
        out.append(f"ТЕКСТ (початок): {text}")
    out.append("")
    for r in records:
        out.append(f"ЗАПИС id={r['id']}")
        out.append(f"  назва: {r.get('title')}")
        # У наборі з різних новин заголовок статті — половина контексту:
        # без нього «знайти кошти» і «збільшити фонд» виглядають випадковими.
        if r.get("article_title"):
            out.append(f"  з новини: {r['article_title']}")
        if r.get("owner_text"):
            out.append(f"  обіцяв: {r['owner_text']}")
        if r.get("promiser"):
            out.append(f"  обіцяв (з тексту): {r['promiser']}")
        out.append("  строк: " + (pp.fmt_date(r["deadline"]) if r.get("deadline")
                                  else "не називали"))
        if r.get("quote"):
            out.append(f"  цитата: «{r['quote']}»")
        out.append("")
    return "\n".join(out)


async def judge_article(article, records, rules=None):
    """Розкласти набір записів на групи.

    Один виклик на дві задачі: записи ОДНІЄЇ статті (`rules=None`) і записи з
    РІЗНИХ новин, зібрані спільним рідкісним словом (`rules=_RULES_CLUSTER`).
    Форма питання та сама — «розклади ці N на групи», — бо саме вона й
    полагодила дублі всередині статті.

    Повертає [{ids, merge, same_case, confidence, why}] або None при збої
    (мовчання моделі не ухвалює рішень — наступний прогін спитає ще раз).
    """
    if not os.environ.get("ANTHROPIC_API_KEY") or len(records) < 2:
        return None
    prompt = (f"{rules or _RULES_GROUP}\n\n{_group_block(article, records)}\n"
              f"Виклич інструмент groups.")
    try:
        msg = await async_client.messages.create(
            model=JUDGE_MODEL,
            max_tokens=700,
            thinking={"type": "disabled"},
            tools=[_GROUP_TOOL],
            tool_choice={"type": "tool", "name": "groups"},
            messages=[{"role": "user", "content": prompt}],
        )
    except Exception as e:
        print(f"promise_judge (групи): {type(e).__name__}: {e}")
        return None
    try:
        _record_usage(JUDGE_MODEL, msg.usage)
    except Exception:
        pass
    got = next((b_.input for b_ in msg.content if b_.type == "tool_use"), None)
    if not got:
        return None
    known = {int(r["id"]) for r in records}
    out = []
    for g in got.get("groups") or []:
        ids = sorted({int(i) for i in (g.get("ids") or []) if int(i) in known})
        if len(ids) < 2:
            continue          # група з одного — це не група
        # ВИРОК ВИНОСИТЬ КОД. Модель називає властивості, і саме на цьому
        # місці три правки промпту поспіль не спрацювали: «одне й те саме» —
        # висновок, а висновок вона підганяє під контекст статті (23 групи
        # проти 15, і прапори знову разом). Пропускаємо лише те, що вона сама
        # назвала або тією самою дією, яку не можна виконати нарізно, або
        # СТАДІЄЮ одного результату (Олег, 17.08: «ми не будемо моніторити,
        # зробили ПКД чи ні, ми стежимо за самим центром»).
        merge = group_survives(g)
        case = bool(g.get("same_case"))
        if not merge and not case:
            continue
        why = " ".join(str(g.get("why") or "").split())[:140]
        out.append({"ids": ids, "merge": merge, "same_case": case,
                    "confidence": g.get("confidence") or "low", "why": why})
    return out


# Скільки питань тримаємо в польоті. Виклики незалежні один від одного, і
# послідовно сто пар — це три-чотири хвилини мовчазного очікування в чаті
# (заміряно на першому прогоні). Вісім — компроміс: швидко, але не впирається
# в ліміт запитів і не з'їдає з'єднання, коли поруч іде витяг.
CONCURRENCY = 8


async def judge_pairs(mode, pairs, limit=MAX_PAIRS, on_progress=None):
    """Прогнати пачку ПАРАЛЕЛЬНО. Повертає список пар із доданим `verdict`.

    Порядок збережено — він же порядок у файлі, який читає людина.

    Пари без вердикту (збій моделі) лишаються з `verdict=None`: вони не
    зникають і не вважаються вирішеними.
    """
    import asyncio

    todo = [dict(p) for p in pairs[:limit]]
    sem = asyncio.Semaphore(CONCURRENCY)
    done = 0

    async def one(p):
        nonlocal done
        async with sem:
            p["verdict"] = await judge_pair(mode, p["a"], p["b"])
        done += 1
        if on_progress and done % 20 == 0:
            try:
                await on_progress(done, len(todo))
            except Exception:
                pass
        return p

    return list(await asyncio.gather(*(one(p) for p in todo)))


def split(judged, min_confidence="high"):
    """Розкласти на «зливаємо самі», «питаємо людину», «не чіпаємо».

    `high` іде сам — це та сама планка, що в матчері завдань: там вона
    заміряна на реальному потоці й не дала жодного хибного зарахування.
    Усе, у чому суддя не впевнений, лишається питанням, а не рішенням.
    """
    auto, ask, skip = [], [], []
    for p in judged:
        v = p.get("verdict")
        if not v:
            ask.append(p)                    # збій — не рішення, а мовчання
        elif v.get("same") and v.get("confidence") == min_confidence:
            auto.append(p)
        elif v.get("same"):
            ask.append(p)
        else:
            skip.append(p)
    return auto, ask, skip
