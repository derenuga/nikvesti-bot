def _pair_block(mode, a, b):
    if mode == "topic":
        return (f"ТЕМА 1: {a['title']}\n"
                f"ТЕМА 2: {b['title']}")
    def side(x, n):
        out = [f"ЗАПИС {n}:", f"  назва: {x['title']}"]
        if x.get("subject"):
            out.append(f"  предмет: {x['subject']}")
        if x.get("owner_text"):
            out.append(f"  обіцяв: {x['owner_text']}")
        out.append("  строк: " + (pp.fmt_date(x["deadline"]) if x.get("deadline")
                                  else "не називали"))
        if x.get("quote"):
            out.append(f"  цитата: «{x['quote']}»")
        return "\n".join(out)
    return side(a, 1) + "\n\n" + side(b, 2)


async def judge_pair(mode, a, b):
    """Один вердикт. Повертає {same, confidence, why} або None при збої.

    `None`, а не «різні»: мовчання моделі не має тихо ухвалювати рішення —
    наступний прогін спитає ще раз.
    """
    if not os.environ.get("ANTHROPIC_API_KEY"):
        return None
    rules = _RULES_TOPIC if mode == "topic" else _RULES_DUPE
    prompt = f"{rules}\n\n{_pair_block(mode, a, b)}\n\nВиклич інструмент verdict."
    try:
        msg = await async_client.messages.create(
            model=JUDGE_MODEL,
            max_tokens=300,
            thinking={"type": "disabled"},
            tools=[_TOOL],
            tool_choice={"type": "tool", "name": "verdict"},
            messages=[{"role": "user", "content": prompt}],
        )
    except Exception as e:
        print(f"promise_judge: {type(e).__name__}: {e}")
        return None
    try:
        _record_usage(JUDGE_MODEL, msg.usage)
    except Exception:
        pass
    v = next((b_.input for b_ in msg.content if b_.type == "tool_use"), None)
    if v and v.get("why"):
        # Тверда стеля: у першому прогоні модель писала абзаци на чотири
        # рядки. У файлі це терпимо, у картці апки — розвалює верстку, а
        # просити «коротко» без обмеження в коді ненадійно.
        why = " ".join(str(v["why"]).split())
        v["why"] = why if len(why) <= 140 else why[:139].rstrip(" ,.;—-") + "…"
    return v


# Скільки питань тримаємо в польоті. Виклики незалежні один від одного, і
# послідовно сто пар — це три-чотири хвилини мовчазного очікування в чаті
# (заміряно на першому прогоні). Вісім — компроміс: швидко, але не впирається
# в ліміт запитів і не з'їдає з'єднання, коли поруч іде витяг.
CONCURRENCY = 8


async def judge_pairs(mode, pairs, limit=MAX_PAIRS, on_progress=None):
    """Прогнати пачку ПАРАЛЕЛЬНО. Повертає список пар із доданим `verdict`.

    Порядок збережено — він же порядок у файлі, який читає людина.

    Пари без вердикту (збій моделі) лишаються з `verdict=None`: вони не
    зникають і не вважаються вирішеними.
    """
    import asyncio

    todo = [dict(p) for p in pairs[:limit]]
    sem = asyncio.Semaphore(CONCURRENCY)
    done = 0

    async def one(p):
        nonlocal done
        async with sem:
            p["verdict"] = await judge_pair(mode, p["a"], p["b"])
        done += 1
        if on_progress and done % 20 == 0:
            try:
                await on_progress(done, len(todo))
            except Exception:
                pass
        return p

    return list(await asyncio.gather(*(one(p) for p in todo)))


def split(judged, min_confidence="high"):
    """Розкласти на «зливаємо самі», «питаємо людину», «не чіпаємо».

    `high` іде сам — це та сама планка, що в матчері завдань: там вона
    заміряна на реальному потоці й не дала жодного хибного зарахування.
    Усе, у чому суддя не впевнений, лишається питанням, а не рішенням.
    """
    auto, ask, skip = [], [], []
    for p in judged:
        v = p.get("verdict")
        if not v:
            ask.append(p)                    # збій — не рішення, а мовчання
        elif v.get("same") and v.get("confidence") == min_confidence:
            auto.append(p)
        elif v.get("same"):
            ask.append(p)
        else:
            skip.append(p)
    return auto, ask, skip
